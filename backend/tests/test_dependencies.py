class Fixtures:
    """GitHub repositories as histories of file trees, the npm registry ({name: repository field,
    None for none}) and Packagist ({name: minified p2 entries})."""

    def __init__(self, npm=None, packagist=None):
        self.trees, self.npm, self.packagist, self.requests = {}, npm or {}, packagist or {}, []

    def history(self, repo):
        return self.trees.setdefault(repo, [("e" * 40, {})])

    def push(self, repo, changes):
        history = self.history(repo)
        sha = f"{len(history) + 1:040x}"
        history.append((sha, {**history[-1][1], **changes}))
        return sha

    def __call__(self, request):
        self.requests.append(request)
        url, path = request.url, unquote(request.url.raw_path.decode().split("?")[0])
        if url.host == "npm.fixture":
            name, version = path[1:].rsplit("/", 1)
            if name not in self.npm:
                return httpx.Response(404, json={"error": "Not found"})
            if isinstance(self.npm[name], list):  # a body that is not the metadata object
                return httpx.Response(200, json=self.npm[name])
            body = {"name": name, "version": version}
            return httpx.Response(200, json={**body, **({"repository": self.npm[name]} if self.npm[name] else {})})
        if url.host == "packagist.fixture":
            name = path.removeprefix("/p2/").removesuffix(".json")
            if name not in self.packagist:
                return httpx.Response(404)
            return httpx.Response(200, json={"packages": {name: self.packagist[name]}})
        parts = path.split("/")
        history = self.history("/".join(parts[2:4]))
        shas = [sha for sha, _ in history]
        if parts[4] == "branches":
            return httpx.Response(404, json={})
        if parts[4] == "contents":
            assert request.headers["Accept"] == "application/vnd.github.raw+json"
            assert request.headers["Authorization"] == "Bearer fixture-github-token"
            tree = dict(history)[url.params["ref"]]
            text = tree.get("/".join(parts[5:]))
            return httpx.Response(404) if text is None else httpx.Response(200, text=text)
        if parts[4] == "compare":
            base, head = parts[5].split("...")
            unseen = shas[shas.index(base) + 1 : shas.index(head) + 1]
            return httpx.Response(200, json={"status": "ahead", "total_commits": len(unseen),
                                             "commits": [{"sha": sha} for sha in unseen]})
        if len(parts) == 5:  # the commit list, newest first
            return httpx.Response(200, json=[{"sha": sha} for sha in reversed(shas)])
        index = shas.index(parts[5])
        before, after = history[index - 1][1] if index else {}, history[index][1]
        changed = sorted(p for p in {*before, *after} if before.get(p) != after.get(p))
        return httpx.Response(200, json={
            "sha": parts[5],
            "commit": {"message": "Change", "author": {"name": "Fixture"}, "committer": {"date": "2026-11-01T00:00:00Z"}},
            "files": [{"filename": p, "status": "modified", "patch": "@@ -1 +1 @@\n+change"} for p in changed],
        })

    def hosts(self):
        return {request.url.host for request in self.requests}


def serve(monkeypatch, **registries):
    """Points GitHub, npm and Packagist at fixture hosts served by one MockTransport."""
    monkeypatch.setenv("NUMEN_GITHUB_API_URL", "http://github.fixture")
    monkeypatch.setenv("NUMEN_NPM_REGISTRY_URL", "http://npm.fixture")
    monkeypatch.setenv("NUMEN_PACKAGIST_URL", "http://packagist.fixture")
    fixtures = Fixtures(**registries)
    original = Sources.__init__

    def setup(self, *args, **kwargs):
        original(self, *args, **kwargs)
        self.client = httpx.Client(transport=httpx.MockTransport(fixtures))

    monkeypatch.setattr(Sources, "__init__", setup)
    return fixtures


def own_application(client, repo, **overrides):
    created = client.post("/api/applications", json={**BODY, **overrides})
    assert created.status_code == 201, created.text
    ident = created.json()["id"]
    own = client.post(f"/api/applications/{ident}/repositories",
                      json={"role": "own", "source_kind": "github", "source_url": f"https://github.com/{repo}"})
    assert own.status_code == 201, own.text
    return ident


def check(app, client, config, ident):
    """Check now, then run every job it leads to."""
    response = client.post(f"/api/applications/{ident}/checks")
    assert response.status_code == 202, response.text
    while run_once(config, app.state.factory, FixtureBroker()):
        pass
    for item in response.json()["items"]:
        job = client.get(item["status_url"]).json()
        assert job["status"] == "succeeded", job["error"]


def upstreams(client, ident):
    return {r["source_url"]: r for r in client.get(f"/api/applications/{ident}").json()["repositories"]
            if r["role"] == "upstream"}


def derivations(app):
    with app.state.factory() as db:
        return db.scalars(select(Job).where(Job.kind == "derive_upstreams").order_by(Job.created_at)).all()


def test_lockfile_change_adds_new_dependencies_off_and_marks_removed_ones(system, monkeypatch):
    app, client, config = system
    github_account(app)
    fixtures = serve(monkeypatch, npm={
        "react": {"type": "git", "url": "git+https://github.com/facebook/react.git", "directory": "packages/react"},
        "left-pad": "git+https://github.com/stevemao/left-pad.git",
        "lodash": "lodash/lodash",
    })
    fixtures.push("acme/shop", npm_files({"react": "^19.0.0", "left-pad": "^1.3.0"}, {"react": "19.0.0", "left-pad": "1.3.0"}))
    ident = own_application(client, "acme/shop")
    hand = client.post(f"/api/applications/{ident}/repositories",
                       json={"source_kind": "github", "source_url": TOOLS, "locked_version": "1.0.0"})
    assert hand.status_code == 201, hand.text

    # The Own repository's Baseline is followed by its first derivation: everything is on.
    check(app, client, config, ident)
    [first] = derivations(app)
    assert first.status == "succeeded" and first.idempotency_key == f"derive:{ident}:{'0' * 39 + '2'}"
    links = upstreams(client, ident)
    assert sorted(links) == sorted([LEFT_PAD, REACT, TOOLS])
    assert [(links[u]["enabled"], links[u]["locked_version"], links[u]["locked_version_source"], links[u]["packages"])
            for u in (REACT, LEFT_PAD)] == [
        (True, "19.0.0", "manifest", ["npm:react"]), (True, "1.3.0", "manifest", ["npm:left-pad"])]
    requested = {r.url.path for r in fixtures.requests if r.url.host == "npm.fixture"}
    assert requested == {"/react/19.0.0", "/left-pad/1.3.0"}

    # New repositories get their Baseline; a commit that changes no manifest derives nothing.
    check(app, client, config, ident)
    fixtures.push("stevemao/left-pad", {"index.js": "module.exports = pad"})
    fixtures.push("acme/shop", {"README.md": "Shop"})
    check(app, client, config, ident)
    assert len(derivations(app)) == 1
    pad_commits = {c["id"] for c in client.get(f"/api/applications/{ident}/commits").json()["items"]
                   if c["repository_id"] == links[LEFT_PAD]["repository_id"]}
    assert len(pad_commits) == 1

    # A lockfile change adds lodash (off) and removes left-pad.
    head = fixtures.push("acme/shop", npm_files({"react": "^19.0.0", "lodash": "^4.17.21"}, {"react": "19.0.0", "lodash": "4.17.21"}))
    check(app, client, config, ident)
    latest = derivations(app)[-1]
    assert latest.status == "succeeded" and latest.idempotency_key == f"derive:{ident}:{head}"
    after = upstreams(client, ident)
    assert (after[LODASH]["enabled"], after[LODASH]["locked_version"], after[LODASH]["locked_version_source"],
            after[LODASH]["removed_at"]) == (False, "4.17.21", "manifest", None)
    assert after[LEFT_PAD]["removed_at"] is not None and after[LEFT_PAD]["packages"] == ["npm:left-pad"]
    assert after[REACT]["enabled"] is True and after[REACT]["removed_at"] is None
    # The hand-added link is untouched.
    assert [after[TOOLS][k] for k in ("enabled", "removed_at", "locked_version", "locked_version_source", "packages")] == [
        True, None, "1.0.0", "operator", []]
    # left-pad's history stays in the Application's commit list.
    listed = {c["id"] for c in client.get(f"/api/applications/{ident}/commits").json()["items"]}
    assert pad_commits <= listed
    with app.state.factory() as db:
        own = db.scalar(select(ApplicationRepository).where(ApplicationRepository.role == "own"))
        assert own.derived_revision == head
    assert client.get(f"/api/applications/{ident}").json()["unresolved_dependencies"] == []
    job = client.get(f"/api/jobs/{latest.id}").json()
    assert job["subject"]["label"] == "acme/shop" and job["result"]["added"] == [LODASH]
    assert job["result"]["removed"] == [LEFT_PAD]
    assert fixtures.hosts() <= HOSTS


def test_unresolved_package_is_listed_not_dropped(system, monkeypatch):
    app, client, config = system
    github_account(app)
    fixtures = serve(
        monkeypatch,
        npm={"gitlab-pkg": "https://gitlab.com/acme/gitlab-pkg.git", "bare-pkg": None, "@acme/ui": "github:Acme/UI",
             "odd-pkg": ["not", "metadata"]},
        # Minified p2 metadata: 3.7.0 inherits its source from 3.8.0.
        packagist={"monolog/monolog": [
            {"version": "3.8.0", "source": {"type": "git", "url": "https://github.com/Seldaek/monolog.git"}},
            {"version": "3.7.0"},
        ]},
    )
    fixtures.push("acme/shop", {
        "package.json": json.dumps({"dependencies": {
            "ghost-pkg": "^1.0.0", "gitlab-pkg": "^2.0.0", "bare-pkg": "*", "@acme/ui": "^1.0.0",
            "odd-pkg": "^1.0.0"}}),
        "composer.json": json.dumps({"require": {
            "php": ">=8.1", "ext-json": "*", "symfony/console": "^6.4", "monolog/monolog": "^3.0"}}),
        "composer.lock": json.dumps({"packages": [
            {"name": "symfony/console", "version": "v6.4.1",
             "source": {"type": "git", "url": "https://github.com/symfony/console.git"}},
            {"name": "monolog/monolog", "version": "3.7.0", "dist": {"type": "zip"}},
        ]}),
    })
    ident = own_application(client, "acme/shop")
    check(app, client, config, ident)
    [job] = derivations(app)
    assert job.status == "succeeded", job.error
    unresolved = client.get(f"/api/applications/{ident}").json()["unresolved_dependencies"]
    assert [(u["ecosystem"], u["name"], u["version"]) for u in unresolved] == [
        ("npm", "ghost-pkg", None), ("npm", "gitlab-pkg", None), ("npm", "bare-pkg", None),
        ("npm", "odd-pkg", None)]
    reasons = {u["name"]: u["reason"] for u in unresolved}
    assert "not found" in reasons["ghost-pkg"] and "not on GitHub" in reasons["gitlab-pkg"]
    assert "no source repository" in reasons["bare-pkg"]
    assert reasons["odd-pkg"] == "Registry metadata could not be read"
    links = upstreams(client, ident)
    assert {url: (link["locked_version"], link["packages"]) for url, link in links.items()} == {
        "https://github.com/acme/ui": (None, ["npm:@acme/ui"]),
        "https://github.com/symfony/console": ("v6.4.1", ["composer:symfony/console"]),
        "https://github.com/seldaek/monolog": ("3.7.0", ["composer:monolog/monolog"]),
    }
    # Scoped names are encoded; a package without a locked version maps through its latest one;
    # composer.lock's source is used before Packagist.
    paths = [r.url.raw_path.decode() for r in fixtures.requests if r.url.host != "github.fixture"]
    assert sorted(paths) == sorted([
        "/ghost-pkg/latest", "/gitlab-pkg/latest", "/bare-pkg/latest", "/@acme%2Fui/latest", "/odd-pkg/latest",
        "/p2/monolog/monolog.json"])
    assert fixtures.hosts() <= HOSTS


def test_two_applications_using_react_share_one_upstream_repository(system, monkeypatch):
    app, client, config = system
    github_account(app)
    fixtures = serve(monkeypatch, npm={
        "react": "git+https://github.com/facebook/react.git",
        "react-dom": {"type": "git", "url": "git+https://github.com/facebook/react.git", "directory": "packages/react-dom"},
    })
    fixtures.push("acme/shop", npm_files({"react": "^19.0.0"}, {"react": "19.0.0"}))
    fixtures.push("acme/blog", {
        "package.json": json.dumps({"dependencies": {"react": "^19.0.0", "react-dom": "^19.0.0"}}),
        "pnpm-lock.yaml": PNPM_V9,
    })
    shop = own_application(client, "acme/shop")
    blog = own_application(client, "acme/blog", asset_name="Blog")
    for ident in (shop, blog):
        check(app, client, config, ident)
    with app.state.factory.begin() as db:
        [react] = db.scalars(select(Repository).where(Repository.source_url == REACT)).all()
        assert db.scalar(select(func.count()).select_from(Repository)) == 3
        links = db.scalars(select(ApplicationRepository).where(ApplicationRepository.repository_id == react.id)).all()
        assert sorted((link.application_id, link.enabled, link.locked_version, link.locked_version_source, link.packages)
                      for link in links) == sorted([
            (shop, True, "19.0.0", "manifest", ["npm:react"]),
            (blog, True, "19.0.0", "manifest", ["npm:react", "npm:react-dom"])])
        for row in db.scalars(select(Application)):
            row.next_check_at = now() - timedelta(seconds=1)
        assert domain.schedule(db) == 2
        checks = db.scalars(select(Job).where(Job.kind == "source_check", Job.status == "queued")).all()
        assert [job.input["repository_id"] for job in checks].count(react.id) == 1
    assert fixtures.hosts() <= HOSTS


