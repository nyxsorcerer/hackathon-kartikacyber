def npm_files(dependencies, locked):
    """package.json and a v3 package-lock.json."""
    lock = {"lockfileVersion": 3, "packages": {
        "": {"dependencies": dependencies},
        **{f"node_modules/{name}": {"version": version} for name, version in locked.items()},
    }}
    return {"package.json": json.dumps({"dependencies": dependencies}), "package-lock.json": json.dumps(lock)}


